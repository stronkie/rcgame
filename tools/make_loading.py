#!/usr/bin/env python3
"""make_loading.py - paints the loading picture of Stronkie's RC Cup
(320x256, 32 colours, 5 separate bitplanes for the loader's OS ViewPort).
The progress bar and its text line are left empty: the loader draws them.
Writes build/gen/loadpic.rle, loadpic.i, preview_loading.png and itch/cover_630x500.png."""
import math, os, random, sys
from PIL import Image, ImageDraw, ImageFilter
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from make_gfx import rle, ttf
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(HERE), 'build', 'gen')
VER = os.environ.get('VER', '0.1')
random.seed(11)
W, H = 320, 256
import make_gfx as MG
im = MG.track_backdrop(8, 280, 200, 0.62)               # a piece of the Championship Arena
d = ImageDraw.Draw(im)
def outlined(xy, s, font, col, w=2):
    for dx in range(-w, w + 1):
        for dy in range(-w, w + 1):
            if dx or dy: d.text((xy[0] + dx, xy[1] + dy), s, font=font, fill=(0, 0, 0), anchor='mm')
    d.text(xy, s, font=font, fill=col, anchor='mm')
lg = Image.open(os.path.join(os.path.dirname(HERE), 'assets', 'stronkiesoft_logo_x2.png')).convert('RGBA')
im.paste(lg, (160 - lg.width // 2, 0), lg)
MG.logo_text(im, 70, 36)
MG.big_car(im, 10, 176, 4, 1, [(100, 0, 0), (220, 30, 30), (255, 160, 150)], 3)
MG.big_car(im, 262, 176, 2, 13, [(0, 20, 60), (50, 110, 230), (150, 200, 255)], 3)
outlined((160, 100), 'ISOMETRIC TOY CAR RACING FOR THE AMIGA 500', ttf(8), (255, 214, 40), 1)
outlined((160, 119), ('V%s  FINAL RELEASE' if VER.startswith('1') else 'V%s  TEST VERSION') % VER, ttf(10), (140, 220, 255), 1)
outlined((160, 134), 'Created By Mark Stronks, Stronkie Soft', ttf(9, bold=False), (230, 230, 230), 1)
cv = im.copy()
c2 = cv.resize((640, 512), Image.NEAREST).crop((5, 6, 635, 506))
os.makedirs(os.path.join(os.path.dirname(HERE), 'itch'), exist_ok=True)
c2.save(os.path.join(os.path.dirname(HERE), 'itch', 'cover_630x500.png'))
# progress bar frame
BAR = (58, 152, 264, 162)
TXT = (56, 165, 268, 175)
d.rectangle([BAR[0] - 2, BAR[1] - 2, BAR[2] + 2, BAR[3] + 2], fill=(220, 220, 230))
d.rectangle([TXT[0], TXT[1], TXT[2], TXT[3]], fill=(10, 30, 20))
FIXED = [(10, 10, 30), (40, 200, 240), (20, 130, 190), (255, 226, 30), (225, 150, 0), (255, 160, 200), (0, 0, 0), (255, 255, 255), (255, 250, 225), (220, 200, 150), (120, 90, 60), (25, 25, 45), (215, 20, 30),
         (20, 80, 215), (250, 120, 0), (255, 215, 60), (140, 220, 255), (110, 60, 25), (170, 110, 60)]
auto = im.quantize(28 - len(FIXED), method=Image.MEDIANCUT).getpalette()[:(28 - len(FIXED)) * 3]
base = [v for c in FIXED for v in c] + auto
pimg = Image.new('P', (1, 1)); pimg.putpalette(base + [0] * (768 - len(base)))
q = im.quantize(palette=pimg, dither=Image.FLOYDSTEINBERG)
pal = base + [8, 30, 16, 255, 200, 40, 10, 30, 20, 235, 235, 225]
q.putpalette(pal + [0] * (768 - len(pal)))
pal12 = [((pal[i * 3] + 8) // 17, (pal[i * 3 + 1] + 8) // 17, (pal[i * 3 + 2] + 8) // 17) for i in range(32)]
pal12 = [tuple(min(15, v) for v in c) for c in pal12]
bar_bg, bar_fg, txt_bg, txt_c = 28, 29, 30, 31
px = q.load()
for y in range(BAR[1], BAR[3] + 1):
    for x in range(BAR[0], BAR[2] + 1): px[x, y] = bar_bg
for y in range(TXT[1], TXT[3] + 1):
    for x in range(TXT[0], TXT[2] + 1): px[x, y] = txt_bg
planes = bytearray()
for p in range(5):
    for y in range(256):
        for xb in range(40):
            b = 0
            for i in range(8):
                if (px[xb * 8 + i, y] >> p) & 1: b |= 0x80 >> i
            planes.append(b)
open(os.path.join(OUT, 'loadpic.rle'), 'wb').write(rle(bytes(planes)))
L = ['; generated by tools/make_loading.py']
L.append('loadpal:\tdc.w\t' + ','.join('$%x%x%x' % c for c in pal12))
L.append('BAR_X0\tequ\t%d\nBAR_Y0\tequ\t%d\nBAR_X1\tequ\t%d\nBAR_Y1\tequ\t%d' % BAR)
L.append('TXT_X\tequ\t%d\nTXT_Y\tequ\t%d' % (TXT[0] // 8 + 1, TXT[1] + 1))
L.append('C_BARBG\tequ\t%d\nC_BARFG\tequ\t%d\nC_TXT\tequ\t%d\nC_TXTBG\tequ\t%d' % (bar_bg, bar_fg, txt_c, txt_bg))
open(os.path.join(OUT, 'loadpic.i'), 'w').write('\n'.join(L) + '\n')
q.convert('RGB').resize((640, 512), Image.NEAREST).save(os.path.join(OUT, 'preview_loading.png'))
print('loading picture: %d bytes packed' % len(rle(bytes(planes))))
